def snake(s: str) -> str:
    out = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    out = re.sub(r"[^A-Za-z0-9]+", "_", out).strip("_").lower()
    return out if re.match(r"[a-z]", out) else "v_" + out


def code_segment(code: str) -> str:
    """`rate_limited` -> rate_limited; `INTERNAL_ERROR` -> upper_internal_error, so the two spellings of
    `forbidden`, `not_found` and `invalid_request` (both live on the wire) stay distinct."""
    seg = re.sub(r"[^a-z0-9_]", "_", code.lower())
    return ("upper_" + seg) if code != code.lower() else seg


def entry(en, fr, ctx, screen, tier, note, args=None):
    e = {"en": en, "ctx": ctx, "screen": screen, "tier": tier}
    if args:
        e["args"] = args
    if fr is not None:
        e["fr"] = fr
        e["state"] = "draft"
    e["note"] = note
    return e


def api_errors() -> tuple[dict, str]:
    src = json.loads((CONTRACTS / "api-errors.json").read_text(encoding="utf-8"))
    items = src["itemsPlaceholder"].strip("{}")
    table: dict = {}
    sentences, without_list = [], []
    for code, c in src["codes"].items():
        seg = code_segment(code)
        args = {items: "str"} if src["itemsPlaceholder"] in c["en"] else None
        note = f"The sentence for the server's error code `{code}`, verbatim from contracts/i18n/api-errors.json."
        if args:
            note += f" {{{items}}} is a list of {c['listField']}, already joined."
        table[seg] = entry(c["en"], c.get("fr"), "error", "errors (server codes)", "T2", note, args)
        sentences.append((code, f"api_error_{seg}"))
        if "enWithoutList" in c:
            table[seg + "_without_list"] = entry(
                c["enWithoutList"], c.get("frWithoutList"), "error", "errors (server codes)", "T2",
                f"The sentence for `{code}` when the response names no {c['listField']}.",
            )
            without_list.append((code, f"api_error_{seg}_without_list"))
    data = {"meta": {"catalog": "api_errors", "platform": "android"}, "api_error": table}
    fallback = code_segment(src["fallbackCode"])
    lines = [
        f"// {HEADER.format(src='api-errors.json')}",
        "package com.distronode.districtai.l10n",
        "",
        "import com.distronode.districtai.R",
        "",
        "/** Each error code the server can send, to its sentence. */",
        "internal val API_ERROR_SENTENCES: Map<String, Int> = mapOf(",
        *[f'    "{code}" to R.string.{name},' for code, name in sentences],
        ")",
        "",
        "/** The codes whose sentence names a list, to the sentence used when the response carries none. */",
        "internal val API_ERROR_SENTENCES_WITHOUT_LIST: Map<String, Int> = mapOf(",
        *[f'    "{code}" to R.string.{name},' for code, name in without_list],
        ")",
        "",
        "/** The sentence for a code this build does not know, when the screen has none of its own. */",
        f"internal val API_ERROR_FALLBACK: Int = R.string.api_error_{fallback}",
        "",
        "/** How the web joins a list into an error sentence (`listSeparator`). */",
        f"internal const val API_ERROR_LIST_SEPARATOR: String = {json.dumps(src['listSeparator'])}",
        "",
    ]
    return data, "\n".join(lines)


def display(value: str, rule: str) -> str:
    """The value as the app shows it, as catalog text: a brace in a value (`http-{status}`) is literal,
    so it is doubled, which the catalog reads as one brace rather than a placeholder."""
    if rule == "upper":
        shown = value.upper()
    elif rule == "humanize":
        shown = humanize(value)
    else:
        shown = value
    return shown.replace("{", "{{").replace("}", "}}")


def core_label(value: str) -> str:
    """The cores' English for a value the portal has no label for (district-core-swift gen-l10n.py's
    `humanize`): hyphens and underscores as spaces, the first letter capitalized."""
    words = value.strip().replace("-", " ").replace("_", " ")
    return words[:1].upper() + words[1:]


def humanize(key: str) -> str:
    """DossierField.kt's humanizeKey: snake_case and camelCase split into words, then sentence case."""
    spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", key.replace("_", " ")).strip()
    if not spaced:
        return key
    first = spaced[:1].upper() + spaced[1:]
    return first[0] + first[1:].lower()


def wire_labels() -> tuple[dict, str]:
    src = json.loads((CONTRACTS / "wire-vocabulary.json").read_text(encoding="utf-8"))
    table: dict = {}
    enums = []
    for cat, (enum_name, rule, screen) in WIRE_CATEGORIES.items():
        spec = src["categories"][cat]
        prefix = snake(cat)
        pairs = []
        for v in spec["values"]:
            # ⛔ A VALUE SPELLED `unknown` (callStatus, numberProvider) GETS `value_unknown`. Its plain key
            # is the category's label for a value this app does not know, which takes the value as an
            # argument; mapping the value there drew "%1$s" for a call whose status is `unknown`.
            seg = f"{prefix}_{'value_unknown' if snake(v['value']) == 'unknown' else snake(v['value'])}"
            portal = v.get("en")
            if rule == "label":
                note = f"The {cat} value `{v['value']}` as the server sends it, shown with the portal's label"
                note += f" (\"{portal}\")." if portal else "; the portal has none, so English is the value humanized."
            elif rule == "portal":
                note = f"The {cat} value `{v['value']}` as the server sends it, shown with the portal's label"
                note += f" (\"{portal}\")." if portal else "; the portal has none, so English shows the value as sent."
            else:
                note = f"The {cat} value `{v['value']}` as the server sends it. This app has always shown it as sent"
                note += {"upper": " (upper-cased).", "humanize": " (as a heading, split into words)."}.get(rule, ".")
                note += f" The portal's English label is \"{portal}\"." if portal else " The portal has no label for it."
            long = v.get("frLong")
            if long:
                note += f" Its long French name is \"{long}\"."
            if rule == "label":
                shown = display(portal or core_label(v["value"]), "raw")
            elif rule == "portal" and portal:
                shown = display(portal, "raw")
            else:
                shown = display(v["value"], rule)
            table[seg] = entry(shown, v.get("fr"), "label", screen, "T3", note)
            if rule == "label":
                # What English read until 3.0.1, so the reviewed French survives the move (keep_translations).
                table[seg][WAS] = display(v["value"], "raw")
            pairs.append((v["value"], f"wire_{seg}"))
        fallback = spec.get("fallback")
        if fallback:
            # ⛔ THE CATEGORY'S OWN FALLBACK WINS OVER THE GENERIC LABEL, in both languages, as the cores
            # do: a number status this app does not know reads "Active" / « Actif », not the raw value.
            table[f"{prefix}_unknown"] = entry(
                fallback["en"], fallback.get("fr"), "label", screen, "T3",
                f"What a {cat} value this app does not know reads as: the category's own `fallback` in"
                " contracts/i18n/wire-vocabulary.json, in both languages.",
            )
        else:
            table[f"{prefix}_unknown"] = entry(
                "{value}", None, "label", screen, "T3",
                f"A {cat} value this app does not know, passed through as {{value}}"
                + {"upper": " (upper-cased)", "humanize": " (as a heading, split into words)"}.get(rule, "")
                + ". English shows it as sent, as it always has."
                " In French, name it generically and keep {value} in it, e.g. a status this app does not know.",
                {"value": "str"},
            )
        enums.append((enum_name, rule, pairs, f"wire_{prefix}_unknown", not fallback))
    for p in src["placeholders"]:
        # ⛔ THE ENGLISH IS THE PLACEHOLDER AS THE SERVER WRITES IT, which is what a screen that passes it
        # through has always shown; the French is the contract's where it has one.
        table[placeholder_segment(p["value"])] = entry(
            display(p["value"], "raw"), p.get("fr"), "label", PLACEHOLDER_SCREEN, "T3",
            "Text the service stores or sends in English in place of a real value, in "
            + "; ".join(p["fields"]) + ". Shown where that value is shown.",
        )
    data = {"meta": {"catalog": "wire_labels", "platform": "android"}, "wire": table}
    lines = [
        f"// {HEADER.format(src='wire-vocabulary.json')}",
        "package com.distronode.districtai.l10n",
        "",
        "import com.distronode.districtai.R",
        "",
        "/**",
        " * Every wire-vocabulary category: each known value to its label, the label for an",
        " * unknown value (which takes the value as its one argument), and whether the value is upper-cased first.",
        " *",
        " * [unknownTakesValue] is false for a category with its own `fallback`, whose unknown label is a fixed",
        " * word (\"Active\") rather than one that names the value.",
        " */",
        "internal enum class WireCategory(",
        "    val labels: Map<String, Int>,",
        "    val unknown: Int,",
        "    val upperCase: Boolean,",
        "    val unknownTakesValue: Boolean,",
        ") {",
    ]
    for enum_name, rule, pairs, unknown, takes_value in enums:
        lines.append(f"    {enum_name}(")
        lines.append("        labels = mapOf(")
        lines += [f'            "{v}" to R.string.{n},' for v, n in pairs]
        lines.append("        ),")
        lines.append(f"        unknown = R.string.{unknown},")
        lines.append(f"        upperCase = {'true' if rule == 'upper' else 'false'},")
        lines.append(f"        unknownTakesValue = {'true' if takes_value else 'false'},")
        lines.append("    ),")
    lines += ["}", ""]
    lines += placeholder_tables(src["placeholders"])
    return data, "\n".join(lines)


PLACEHOLDER_SCREEN = "wire placeholder"


def placeholder_segment(value: str) -> str:
    """`No summary available.` -> placeholder_no_summary_available, the name the cores use."""
    return f"placeholder_{snake(value)}"


def placeholder_tables(placeholders: list) -> list[str]:
    """The `placeholders` list as Kotlin: every value the server stores or sends in English in place of a
    real one, and the earlier spellings (`aliases`) a stored row may still hold. json.dumps escapes any
    non-ASCII character (`\\u2014`), which Kotlin reads the same way."""
    aliased = [p for p in placeholders if p.get("aliases")]
    return [
        "/**",
        " * Every placeholder the server stores or sends in English in place of a real value (`Unknown`,",
        " * `No summary available.`), in its current spelling.",
        " */",
        "internal val WIRE_PLACEHOLDERS: Set<String> = setOf(",
        *[f"    {json.dumps(p['value'])}," for p in placeholders],
        ")",
        "",
        "/** Each placeholder that has earlier spellings, to those spellings: rows stored before the change keep them. */",
        "internal val WIRE_PLACEHOLDER_ALIASES: Map<String, List<String>> = mapOf(",
        *[
            f"    {json.dumps(p['value'])} to listOf({', '.join(json.dumps(a) for a in p['aliases'])}),"
            for p in aliased
        ],
        ")",
        "",
        "/**",
        " * Every placeholder, in its current spelling and every earlier one, to its label: the same words in",
        " * English, the reader's language in French.",
        " */",
        "internal val WIRE_PLACEHOLDER_LABELS: Map<String, Int> = mapOf(",
        *[
            f"    {json.dumps(spelling)} to R.string.wire_{placeholder_segment(p['value'])},"
            for p in placeholders
            for spelling in [p["value"], *p.get("aliases", [])]
        ],
        ")",
        "",
    ]


# The translation fields an entry keeps across a regeneration while its English is unchanged, so
# `l10n.py import` writes French into these catalogs like into any other (as the cores' generators do).
KEPT = ("fr", "state", "same_ok", "fr_variant", "waive", "max", "id")


def keep_translations(data: dict, previous: Path) -> dict:
    """`data` with the translation fields of `previous` (the committed catalog) put back on every
    entry whose English is unchanged, or whose English moved from the raw value to the portal's label
    (the French named the same value all along). A changed English, or an entry the catalog has no
    French for, takes the contract's French."""
    old = (
        {e.key: e.fields for e in l10n.load_catalog(previous).entries.values()} if previous.is_file() else {}
    )
    for group, table in data.items():
        if group == "meta":
            continue
        for seg, fields in table.items():
            was = fields.pop(WAS, None)
            before = old.get(f"{group}.{seg}")
            if before is None or before.get("en") not in (fields["en"], was):
                continue
            for field in KEPT:
                if field in before:
                    fields[field] = before[field]
    return data


def outputs() -> list[tuple[Path, str]]:
    out = []
    for name, (data, kotlin), kt in (
        ("api_errors", api_errors(), "ApiErrorCatalog.kt"),
        ("wire_labels", wire_labels(), "WireCategory.kt"),
    ):
        path = ROOT / "l10n" / f"{name}.toml"
        data = keep_translations(data, path)
        out.append((path, l10n.emit_catalog(l10n.catalog_from_data(path, data))))
        out.append((KOTLIN_DIR / kt, kotlin))
    return out


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    p.add_argument("--check", action="store_true", help="fail if a generated file differs")
    args = p.parse_args(argv)
    stale = []
    for path, text in outputs():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    for s in stale:
        print(f"{s}: differs from what scripts/l10n-contracts.py writes (run it)", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Generate the error-code and wire-label catalogs (and their Kotlin lookup tables) from contracts/i18n.

    python3 scripts/l10n-contracts.py           write l10n/{api_errors,wire_labels}.toml and the Kotlin tables
    python3 scripts/l10n-contracts.py --check   fail if any of them differs from what this script writes

Then `tools/l10n/l10n.py gen` turns each catalog into its resource file, exactly as for l10n/android.toml
(see CONTRIBUTING.md, "Strings").

The inputs are the website's byte-pinned contract files, vendored unchanged under contracts/i18n/:

- api-errors.json: every error code the server can send, in the body's `code` or in the
  `X-Distronode-Error-Code` header, with the web's English and French sentence. One catalog entry per code.
- wire-vocabulary.json: the raw values the server sends for statuses, sentiments, regions and the like,
  with the portal's labels. One catalog entry per value of each category this app displays. Its
  `placeholders` (English the server writes in place of a real value, with earlier spellings under
  `aliases`) become two Kotlin tables and no catalog entry: a screen recognises one and shows its own copy.

⛔ THE ENGLISH OF A WIRE LABEL IS WHAT THIS APP SHOWS TODAY, NOT THE PORTAL'S LABEL. The app has always
displayed these values raw (a call reads "completed", a region "CA"), and W1 changes no English, so `en`
reproduces that display and the portal's English is kept in the translator note. The French is the
portal's French. A value the vocabulary does not list falls back to the category's `unknown` entry,
whose English is the raw value again.

Python 3.11 or newer, standard library only. It imports tools/l10n/l10n.py for the canonical TOML writer.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "l10n"))
import l10n  # noqa: E402  (the vendored tool, found through the path above)

CONTRACTS = ROOT / "contracts" / "i18n"
KOTLIN_DIR = ROOT / "app" / "src" / "main" / "kotlin" / "com" / "distronode" / "districtai" / "l10n"
HEADER = "@generated by scripts/l10n-contracts.py from contracts/i18n/{src}. Do not edit; run the script."

# Category -> (Kotlin enum name, how today's English displays a raw value, screen).
# `raw` shows the value as sent; `upper` upper-cases it (the workspace region chip).
WIRE_CATEGORIES = {
    "callStatus": ("CALL_STATUS", "raw", "call log, call detail, overview"),
    "sentiment": ("SENTIMENT", "raw", "call detail"),
    "disposition": ("DISPOSITION", "raw", "call detail"),
    "transferStatus": ("TRANSFER_STATUS", "raw", "call detail"),
    "transferReason": ("TRANSFER_REASON", "raw", "call detail"),
    "funnelStage": ("FUNNEL_STAGE", "raw", "analytics"),
    "analyticsSentiment": ("ANALYTICS_SENTIMENT", "raw", "analytics"),
    "region": ("REGION", "upper", "overview"),
}


def snake(s: str) -> str:
    out = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    out = re.sub(r"[^A-Za-z0-9]+", "_", out).strip("_").lower()
    return out if re.match(r"[a-z]", out) else "v_" + out


def code_segment(code: str) -> str:
    """`rate_limited` -> rate_limited; `INTERNAL_ERROR` -> upper_internal_error, so the two spellings of
    `forbidden`, `not_found` and `invalid_request` (both live on the wire) stay distinct."""
    seg = re.sub(r"[^a-z0-9_]", "_", code.lower())
    return ("upper_" + seg) if code != code.lower() else seg


def entry(en, fr, ctx, screen, tier, note, args=None):
    e = {"en": en, "ctx": ctx, "screen": screen, "tier": tier}
    if args:
        e["args"] = args
    if fr is not None:
        e["fr"] = fr
        e["state"] = "draft"
    e["note"] = note
    return e


def api_errors() -> tuple[dict, str]:
    src = json.loads((CONTRACTS / "api-errors.json").read_text(encoding="utf-8"))
    items = src["itemsPlaceholder"].strip("{}")
    table: dict = {}
    sentences, without_list = [], []
    for code, c in src["codes"].items():
        seg = code_segment(code)
        args = {items: "str"} if src["itemsPlaceholder"] in c["en"] else None
        note = f"The sentence for the server's error code `{code}`, verbatim from contracts/i18n/api-errors.json."
        if args:
            note += f" {{{items}}} is a list of {c['listField']}, already joined."
        table[seg] = entry(c["en"], c.get("fr"), "error", "errors (server codes)", "T2", note, args)
        sentences.append((code, f"api_error_{seg}"))
        if "enWithoutList" in c:
            table[seg + "_without_list"] = entry(
                c["enWithoutList"], c.get("frWithoutList"), "error", "errors (server codes)", "T2",
                f"The sentence for `{code}` when the response names no {c['listField']}.",
            )
            without_list.append((code, f"api_error_{seg}_without_list"))
    data = {"meta": {"catalog": "api_errors", "platform": "android"}, "api_error": table}
    fallback = code_segment(src["fallbackCode"])
    lines = [
        f"// {HEADER.format(src='api-errors.json')}",
        "package com.distronode.districtai.l10n",
        "",
        "import com.distronode.districtai.R",
        "",
        "/** Each error code the server can send, to its sentence. */",
        "internal val API_ERROR_SENTENCES: Map<String, Int> = mapOf(",
        *[f'    "{code}" to R.string.{name},' for code, name in sentences],
        ")",
        "",
        "/** The codes whose sentence names a list, to the sentence used when the response carries none. */",
        "internal val API_ERROR_SENTENCES_WITHOUT_LIST: Map<String, Int> = mapOf(",
        *[f'    "{code}" to R.string.{name},' for code, name in without_list],
        ")",
        "",
        "/** The sentence for a code this build does not know, when the screen has none of its own. */",
        f"internal val API_ERROR_FALLBACK: Int = R.string.api_error_{fallback}",
        "",
        "/** How the web joins a list into an error sentence (`listSeparator`). */",
        f"internal const val API_ERROR_LIST_SEPARATOR: String = {json.dumps(src['listSeparator'])}",
        "",
    ]
    return data, "\n".join(lines)


def display(value: str, rule: str) -> str:
    return value.upper() if rule == "upper" else value


def wire_labels() -> tuple[dict, str]:
    src = json.loads((CONTRACTS / "wire-vocabulary.json").read_text(encoding="utf-8"))
    table: dict = {}
    enums = []
    for cat, (enum_name, rule, screen) in WIRE_CATEGORIES.items():
        spec = src["categories"][cat]
        prefix = snake(cat)
        pairs = []
        for v in spec["values"]:
            seg = f"{prefix}_{snake(v['value'])}"
            portal = v.get("en")
            note = f"The {cat} value `{v['value']}` as the server sends it. This app has always shown it as sent"
            note += " (upper-cased)." if rule == "upper" else "."
            note += f" The portal's English label is \"{portal}\"." if portal else " The portal has no label for it."
            long = v.get("frLong")
            if long:
                note += f" Its long French name is \"{long}\"."
            table[seg] = entry(display(v["value"], rule), v.get("fr"), "label", screen, "T3", note)
            pairs.append((v["value"], f"wire_{seg}"))
        table[f"{prefix}_unknown"] = entry(
            "{value}", None, "label", screen, "T3",
            f"A {cat} value this app does not know, passed through as {{value}}"
            + (" (upper-cased)" if rule == "upper" else "") + ". English shows it as sent, as it always has."
            " In French, name it generically and keep {value} in it, e.g. a status this app does not know.",
            {"value": "str"},
        )
        enums.append((enum_name, rule, pairs, f"wire_{prefix}_unknown"))
    data = {"meta": {"catalog": "wire_labels", "platform": "android"}, "wire": table}
    lines = [
        f"// {HEADER.format(src='wire-vocabulary.json')}",
        "package com.distronode.districtai.l10n",
        "",
        "import com.distronode.districtai.R",
        "",
        "/**",
        " * The wire-vocabulary categories this app displays: each known value to its label, the label for an",
        " * unknown value (which takes the value as its one argument), and whether the value is upper-cased first.",
        " */",
        "internal enum class WireCategory(val labels: Map<String, Int>, val unknown: Int, val upperCase: Boolean) {",
    ]
    for enum_name, rule, pairs, unknown in enums:
        lines.append(f"    {enum_name}(")
        lines.append("        labels = mapOf(")
        lines += [f'            "{v}" to R.string.{n},' for v, n in pairs]
        lines.append("        ),")
        lines.append(f"        unknown = R.string.{unknown},")
        lines.append(f"        upperCase = {'true' if rule == 'upper' else 'false'},")
        lines.append("    ),")
    lines += ["}", ""]
    lines += placeholder_tables(src["placeholders"])
    return data, "\n".join(lines)


def placeholder_tables(placeholders: list) -> list[str]:
    """The `placeholders` list as Kotlin: every value the server stores or sends in English in place of a
    real one, and the earlier spellings (`aliases`) a stored row may still hold. json.dumps escapes any
    non-ASCII character (`\\u2014`), which Kotlin reads the same way."""
    aliased = [p for p in placeholders if p.get("aliases")]
    return [
        "/**",
        " * Every placeholder the server stores or sends in English in place of a real value (`Unknown`,",
        " * `No summary available.`), in its current spelling.",
        " */",
        "internal val WIRE_PLACEHOLDERS: Set<String> = setOf(",
        *[f"    {json.dumps(p['value'])}," for p in placeholders],
        ")",
        "",
        "/** Each placeholder that has earlier spellings, to those spellings: rows stored before the change keep them. */",
        "internal val WIRE_PLACEHOLDER_ALIASES: Map<String, List<String>> = mapOf(",
        *[
            f"    {json.dumps(p['value'])} to listOf({', '.join(json.dumps(a) for a in p['aliases'])}),"
            for p in aliased
        ],
        ")",
        "",
    ]


def outputs() -> list[tuple[Path, str]]:
    out = []
    for name, (data, kotlin), kt in (
        ("api_errors", api_errors(), "ApiErrorCatalog.kt"),
        ("wire_labels", wire_labels(), "WireCategory.kt"),
    ):
        path = ROOT / "l10n" / f"{name}.toml"
        out.append((path, l10n.emit_catalog(l10n.catalog_from_data(path, data))))
        out.append((KOTLIN_DIR / kt, kotlin))
    return out


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    p.add_argument("--check", action="store_true", help="fail if a generated file differs")
    args = p.parse_args(argv)
    stale = []
    for path, text in outputs():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    for s in stale:
        print(f"{s}: differs from what scripts/l10n-contracts.py writes (run it)", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
